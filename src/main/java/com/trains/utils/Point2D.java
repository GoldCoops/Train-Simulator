package com.trains.utils;

public class Point2D {
    /**
     * A 2D point class
     */
    public double x;
    public double y;

    /**
     * Constructor for a 2D Point
     * @param x the x coordinate
     * @param y the y coordinate
     */
    public Point2D(double x, double y) {
        this.x = x;
        this.y = y;
    }
}
